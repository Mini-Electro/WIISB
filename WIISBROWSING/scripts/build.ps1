# Builds WIISBROWSING from source: tests -> self-contained publish -> installer -> release folder.
#   powershell -ExecutionPolicy Bypass -File scripts\build.ps1            (full build)
#   powershell -ExecutionPolicy Bypass -File scripts\build.ps1 -SkipTests
param([switch]$SkipTests, [string]$Version = "0.1.0", [string]$UpdateRepo = "")
$ErrorActionPreference = "Stop"
$root = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
Set-Location $root

# .NET SDK: use the one on PATH, else the per-user install made by dotnet-install.
if (-not (Get-Command dotnet -ErrorAction SilentlyContinue) -or -not (& dotnet --list-sdks 2>$null)) {
    $env:DOTNET_ROOT = "$env:USERPROFILE\.dotnet"; $env:Path = "$env:USERPROFILE\.dotnet;$env:Path"
}
$env:DOTNET_CLI_TELEMETRY_OPTOUT = 1; $env:DOTNET_NOLOGO = 1

# Icon + logo (original artwork generated by script; skipped if already present)
if (-not (Test-Path "src\WIISBROWSING.App\Assets\wiisbrowsing.ico")) { & "$PSScriptRoot\make-icon.ps1" }

if (-not $SkipTests) {
    Write-Host "== Unit tests ==" -ForegroundColor Cyan
    dotnet test tests\WIISBROWSING.UnitTests -nologo -v q
    if ($LASTEXITCODE -ne 0) { throw "Unit tests failed" }
}

Write-Host "== Publish (self-contained, win-x64) ==" -ForegroundColor Cyan
if (Test-Path publish\win-x64) { Remove-Item publish\win-x64 -Recurse -Force }
dotnet publish src\WIISBROWSING.App -c Release -r win-x64 --self-contained true -o publish\win-x64 -p:DebugType=none -p:DebugSymbols=false -p:Version=$Version "-p:UpdateRepo=$UpdateRepo" -nologo -v q
if ($LASTEXITCODE -ne 0) { throw "Publish failed" }

Write-Host "== Installer ==" -ForegroundColor Cyan
$makensis = @("$env:LOCALAPPDATA\tauri\NSIS\makensis.exe", "${env:ProgramFiles(x86)}\NSIS\makensis.exe", "$env:ProgramFiles\NSIS\makensis.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $makensis) { throw "makensis.exe (NSIS) was not found. Install NSIS from https://nsis.sourceforge.io or build the Tauri apps once (they download it)." }
New-Item -ItemType Directory -Force release | Out-Null
$setup = "release\WIISBROWSING_${Version}_x64-setup.exe"
& $makensis /V2 "/DVERSION=$Version" "/DSRC=$root\publish\win-x64" "/DSRCICON=$root\src\WIISBROWSING.App\Assets\wiisbrowsing.ico" "/DOUT=$root\$setup" installer\WIISBROWSING.nsi
if ($LASTEXITCODE -ne 0) { throw "makensis failed" }

# A portable copy (no installer needed) and checksums
if (Test-Path release\WIISBROWSING) { Remove-Item release\WIISBROWSING -Recurse -Force }
Copy-Item publish\win-x64 release\WIISBROWSING -Recurse
$hashes = Get-ChildItem $setup, release\WIISBROWSING\WIISBROWSING.exe | Get-FileHash -Algorithm SHA256 | ForEach-Object { [ordered]@{ File = (Resolve-Path -Relative $_.Path); Hash = $_.Hash } }
($hashes | ConvertTo-Json) | Set-Content release\SHA256.json -Encoding utf8

Write-Host "`nDone:" -ForegroundColor Green
Get-Item $setup | ForEach-Object { "  installer : {0}  ({1:N1} MB)" -f $_.FullName, ($_.Length / 1MB) }
"  portable  : $root\release\WIISBROWSING\WIISBROWSING.exe"
